void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Hive for WallRio CMS — adapters are generated by build_runner
  await Hive.initFlutter();
  Hive.registerAdapter(SavedFilePathImplAdapter());
  Hive.registerAdapter(LocalVersionImplAdapter());

  // Desktop window
  if (Platform.isWindows || Platform.isMacOS || Platform.isLinux) {
    await WindowService.init();
    await startUpWindowsUtils();
  }

  // Android permissions
  if (Platform.isAndroid) {
    await [
      Permission.storage,
      Permission.manageExternalStorage,
    ].request();
  }

  // Video player
  VideoPlayerMediaKit.ensureInitialized(
    android: true,
    iOS: true,
    macOS: true,
    windows: true,
  );

  // Global error widget
  ErrorWidget.builder = (details) => Container(
        decoration: const BoxDecoration(
          color: AppColors.darkSurface0,
          borderRadius: AppRadius.radiusMd,
        ),
        alignment: Alignment.center,
        padding: const EdgeInsets.all(16),
        child: Text(
          details.exceptionAsString(),
          textAlign: TextAlign.center,
          style: const TextStyle(color: AppColors.errorDark, fontSize: 11),
        ),
      );

  final prefs = await SharedPreferences.getInstance();

  runApp(
    ProviderScope(
      overrides: [sharedPrefsProvider.overrideWithValue(prefs)],
      child: const RootApp(),
    ),
  );
}

