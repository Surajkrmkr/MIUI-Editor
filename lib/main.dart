class _AppCard extends StatefulWidget {
  const _AppCard({required this.app, required this.onTap});
  final _AppEntry app;
  final VoidCallback onTap;

  @override
  State<_AppCard> createState() => _AppCardState();
}

class _AppCardState extends State<_AppCard> with SingleTickerProviderStateMixin {
  late final AnimationController _hoverCtrl;
  late final Animation<double> _enterAnim;

  double _mouseX = 0.5;
  double _mouseY = 0.5;

  @override
  void initState() {
    super.initState();
    _hoverCtrl = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 280),
    );
    _enterAnim = CurvedAnimation(parent: _hoverCtrl, curve: Curves.easeOut);
  }

  @override
  void dispose() {
    _hoverCtrl.dispose();
    super.dispose();
  }

  void _onHover(PointerEvent event) {
    final box = context.findRenderObject() as RenderBox?;
    if (box == null) return;
    final local = box.globalToLocal(event.position);
    setState(() {
      _mouseX = (local.dx / box.size.width).clamp(0.0, 1.0);
      _mouseY = (local.dy / box.size.height).clamp(0.0, 1.0);
    });
  }

  @override
  Widget build(BuildContext context) {
    return MouseRegion(
      cursor: SystemMouseCursors.click,
      onEnter: (_) => _hoverCtrl.forward(),
      onExit: (_) => _hoverCtrl.reverse(),
      onHover: _onHover,
      child: GestureDetector(
        onTap: widget.onTap,
        child: AnimatedBuilder(
          animation: _hoverCtrl,
          builder: (context, _) {
            final t = _enterAnim.value;
            final color = widget.app.color;

            // 3D tilt toward cursor
            final tiltX = (_mouseY - 0.5) * -0.10 * t;
            final tiltY = (_mouseX - 0.5) * 0.10 * t;
            final tiltMatrix = Matrix4.identity()
              ..setEntry(3, 2, 0.001)
              ..rotateX(tiltX)
              ..rotateY(tiltY);

            // Spotlight alignment follows cursor
            final spotX = (_mouseX * 2) - 1;
            final spotY = (_mouseY * 2) - 1;

            return Transform(
              transform: tiltMatrix,
              alignment: Alignment.center,
              child: Container(
                decoration: BoxDecoration(
                  borderRadius: AppRadius.radiusXl,
                  boxShadow: [
                    BoxShadow(
                      color: color.withAlpha((90 * t).toInt()),
                      blurRadius: lerpDouble(6, 40, t)!,
                      offset: Offset(
                        (_mouseX - 0.5) * 10 * t,
                        lerpDouble(2, 20, t)! + (_mouseY - 0.5) * 6 * t,
                      ),
                    ),
                  ],
                ),
                child: ClipRRect(
                  borderRadius: AppRadius.radiusXl,
                  child: Stack(
                    fit: StackFit.expand,
                    children: [
                      // Background image
                      if (widget.app.bgImageDark != null || widget.app.bgImageLight != null)
                        Image.asset(
                          (Theme.of(context).brightness == Brightness.dark
                                  ? widget.app.bgImageDark
                                  : widget.app.bgImageLight) ??
                              widget.app.bgImageDark ??
                              widget.app.bgImageLight!,
                          fit: BoxFit.cover,
                        ),

                      // Dark overlay — lifts on hover
                      Container(
                        color: (Theme.of(context).brightness == Brightness.dark 
                                ? Colors.black 
                                : Colors.white).withAlpha(
                          lerpDouble(115, 50, t)!.toInt(),
                        ),
                      ),

                      // White spotlight following cursor
                      Positioned.fill(
                        child: IgnorePointer(
                          child: Container(
                            decoration: BoxDecoration(
                              gradient: RadialGradient(
                                center: Alignment(spotX, spotY),
                                radius: 0.75,
                                colors: [
                                  Colors.white.withAlpha((55 * t).toInt()),
                                  Colors.transparent,
                                ],
                              ),
                            ),
                          ),
                        ),
                      ),

                      // Accent color bloom at cursor
                      Positioned.fill(
                        child: IgnorePointer(
                          child: Container(
                            decoration: BoxDecoration(
                              gradient: RadialGradient(
                                center: Alignment(spotX, spotY),
                                radius: 0.5,
                                colors: [
                                  color.withAlpha((50 * t).toInt()),
                                  Colors.transparent,
                                ],
                              ),
                            ),
                          ),
                        ),
                      ),

                      // Border glow
                      Container(
                        decoration: BoxDecoration(
                          borderRadius: AppRadius.radiusXl,
                          border: Border.all(
                            color: Color.lerp(
                              Colors.white.withAlpha(30),
                              color.withAlpha(210),
                              t,
                            )!,
                            width: lerpDouble(1.0, 1.5, t)!,
                          ),
                        ),
                      ),

                      // Text — top right
                      Positioned(
                        top: 18,
                        right: 18,
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.end,
                          children: [
                            Text(
                              widget.app.title,
                              style: Theme.of(context)
                                  .textTheme
                                  .titleMedium
                                  ?.copyWith(
                                    fontWeight: FontWeight.w700,
                                    color: Theme.of(context).brightness == Brightness.dark 
                                        ? Colors.white 
                                        : Colors.black87,
                                    shadows: Theme.of(context).brightness == Brightness.dark 
                                        ? [
                                            Shadow(
                                              color: Colors.black.withAlpha(140),
                                              blurRadius: 8,
                                            ),
                                          ]
                                        : null,
                                  ),
                            ),
                            const SizedBox(height: 4),
                            Text(
                              widget.app.subtitle,
                              style: Theme.of(context)
                                  .textTheme
                                  .bodySmall
                                  ?.copyWith(
                                    color: Theme.of(context).brightness == Brightness.dark 
                                        ? Colors.white70 
                                        : Colors.black54,
                                  ),
                            ),
                          ],
                        ),
                      ),
                    ],
                  ),
                ),
              ),
            );
          },
        ),
      ),
    );
  }
}

