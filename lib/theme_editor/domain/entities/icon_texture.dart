enum IconTexture {
  none,
  grain,
  paper,
  linen,
  brushedMetal,
  carbonFiber,
  marble,
  terrazzo,
  halftone,
  dots,
  grid,
  stripes,
  waves,
  topographic,
  glitter,
  wood,
  leather,
  concrete;

  String get label => switch (this) {
    none => 'None',
    grain => 'Grain',
    paper => 'Paper',
    linen => 'Linen',
    brushedMetal => 'Brushed',
    carbonFiber => 'Carbon',
    marble => 'Marble',
    terrazzo => 'Terrazzo',
    halftone => 'Halftone',
    dots => 'Dots',
    grid => 'Grid',
    stripes => 'Stripes',
    waves => 'Waves',
    topographic => 'Topo',
    glitter => 'Glitter',
    wood => 'Wood',
    leather => 'Leather',
    concrete => 'Concrete',
  };
}
