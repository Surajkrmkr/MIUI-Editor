import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:miui_icon_generator/theme_editor/domain/entities/builtin_widget_styles.dart';
import 'package:miui_icon_generator/theme_editor/domain/entities/element_widget.dart';
import 'package:miui_icon_generator/theme_editor/domain/entities/lock_widget.dart';

/// The editor's widget templates and style sets, written out for theme_core
/// so the command line and AI tools offer the same ones. Regenerate with
/// `UPDATE_GOLDENS=1 flutter test test/theme_editor/widget_library_test.dart`.
const _target = 'packages/theme_core/lib/src/library/widget_library.g.dart';

/// [element] without the fields that sit at their defaults.
Map<String, dynamic> _compact(LockElement element) {
  final defaults = LockElement(type: element.type).toJson();
  final json = element.toJson();
  return {
    'type': element.type.name,
    for (final e in json.entries)
      if (e.key != 'type' && jsonEncode(e.value) != jsonEncode(defaults[e.key]))
        e.key: e.value,
  };
}

String _generate() {
  final library = {
    'widgets': [
      for (final w in kPresetWidgets)
        {
          'name': w.name,
          'description': w.description,
          'category': w.category,
          'elements': [for (final e in w.elements) _compact(e)],
        },
    ],
    'styleSets': [
      for (final set in builtinStyleSets)
        {
          'id': set.id,
          'name': set.name,
          'styles': [
            for (final s in set.styles)
              {
                'id': s.id,
                'name': s.name,
                'type': s.type.name,
                'appearance': s.appearance,
              },
          ],
        },
    ],
  };
  final json = const JsonEncoder.withIndent(' ').convert(library);
  expect(json.contains("'''"), isFalse);
  return "// GENERATED by test/theme_editor/widget_library_test.dart; do not edit.\n"
      "// ignore_for_file: lines_longer_than_80_chars\n\n"
      "const widgetLibraryJson = r'''\n$json\n''';\n";
}

void main() {
  test('theme_core carries the editor\'s widgets and style sets', () {
    final generated = _generate();
    final file = File(_target);
    if (Platform.environment['UPDATE_GOLDENS'] == '1') {
      file.writeAsStringSync(generated);
      // ignore: avoid_print
      print('Wrote $_target');
      return;
    }
    expect(
      file.existsSync() ? file.readAsStringSync() : '',
      generated,
      reason:
          'The widgets or styles changed. Regenerate with: '
          'UPDATE_GOLDENS=1 flutter test test/theme_editor/widget_library_test.dart',
    );
  });
}
