/// Background shapes. Paths are built resolution-independently in
/// `IconShapeUtils.path`, so preview and export always match.
enum IconShape {
  squircle,
  circle,
  square,
  cookie4,
  cookie7,
  scallop,
  clover,
  flower,
  sunny,
  burst,
  arch,
  pill,
  hexagon,
  pentagon,
  diamond,
  leaf,
  heart,
  shield,
  blob;

  String get label => switch (this) {
    squircle => 'Squircle',
    circle => 'Circle',
    square => 'Square',
    cookie4 => 'Cookie 4',
    cookie7 => 'Cookie 7',
    scallop => 'Scallop',
    clover => 'Clover',
    flower => 'Flower',
    sunny => 'Sunny',
    burst => 'Burst',
    arch => 'Arch',
    pill => 'Pill',
    hexagon => 'Hexagon',
    pentagon => 'Pentagon',
    diamond => 'Diamond',
    leaf => 'Leaf',
    heart => 'Heart',
    shield => 'Shield',
    blob => 'Blob',
  };
}
